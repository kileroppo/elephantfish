import { chromium } from 'playwright-core'
const b = await chromium.launch({ channel: 'chrome' })
const c = await b.newContext({viewport:{width:1600,height:980}})
const p = await c.newPage()
p.on('requestfailed', r => console.log('FAILED', r.method(), r.url(), '::', r.failure()?.errorText))
p.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text(), m.location?.()?.url) })
await p.goto('http://127.0.0.1:8020/', { waitUntil: 'networkidle' })
await p.waitForTimeout(1000)
console.log('--- reset ---')
await p.evaluate(async () => { await fetch('/api/new', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({engine_side:'red',think_ms:900})}) })
await p.waitForTimeout(2500)
console.log('--- close ---')
await c.close()
await b.close()
console.log('done')
